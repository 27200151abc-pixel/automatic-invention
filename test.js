'use strict';
const fs = require('node:fs');
const assert = require('node:assert/strict');
const progressStore = require('./progress-store.js');
const html = fs.readFileSync('index.html', 'utf8');
assert.match(html, /<html lang="ar" dir="rtl">/, 'Arabic RTL document');
assert.equal(progressStore.STORAGE_KEY, 'verbasprout-progress', 'stable local progress storage key');
assert.match(html, /id="review-errors"/, 'mistake review action exists');
assert.match(html, /id="review-panel"/, 'mistake review panel exists');
assert.match(html, /المراجعة لا تضيف نقاطًا/, 'review mode does not award points');
assert.match(html, /const lessons=\[/, 'lesson data exists');
const lessonIds = [...html.matchAll(/\{id:'([^']+)',q:'/g)].map(match => match[1]);
assert.equal(lessonIds.length, 8, 'eight A1 lesson steps');
assert.equal(new Set(lessonIds).size, lessonIds.length, 'lesson IDs are unique and stable');
assert.match(html, /role="status"/, 'accessible feedback region');
assert.match(html, /@media|auto-fit/, 'responsive layout');
assert.ok(html.includes('<script src="./progress-store.js"></script>'), 'progress module is loaded from the same origin');
assert.doesNotMatch(html, /<script[^>]+src=["']https?:\/\//i, 'no remote script dependencies');
assert.match(html, /let state=saved\(\),index=state\.step,score=state\.score,answered=state\.answered,selected=state\.selected,mistakes=state\.mistakes\.slice\(\);/, 'saved answer and mistake state are restored on reload');
assert.match(html, /mistakes.push\(\{questionId:l\.id,selected:choice\}\)/, 'mistakes are stored by stable lesson ID');
assert.match(html, /lessons.findIndex\(item=>item.id===mistake.questionId\)/, 'review resolves mistakes by stable lesson ID');
assert.doesNotMatch(html, /lisanora/i, 'no Lisanora integration');
assert.match(html, /aria-disabled/, 'answered choices expose their disabled state accessibly');
assert.match(html, /tabIndex=i===selected\?0:-1/, 'keyboard focus moves from the selected answer to Next');
assert.match(html, /الإجابة الصحيحة:/, 'incorrect-answer feedback names the correct choice');

const manifest = JSON.parse(fs.readFileSync('manifest.webmanifest', 'utf8'));
const worker = fs.readFileSync('sw.js', 'utf8');
const icon = fs.readFileSync('icon.svg', 'utf8');
const deploy = fs.readFileSync('.github/workflows/deploy-pages.yml', 'utf8');
const uptime = fs.readFileSync('.github/workflows/uptime-smoke.yml', 'utf8');
assert.equal(manifest.start_url, './', 'PWA start URL is relative for project pages');
assert.equal(manifest.scope, './', 'PWA scope is relative for project pages');
assert.ok(uptime.includes('cron: "*/30 * * * *"'), 'uptime workflow is scheduled every 30 minutes');
assert.ok(uptime.includes('vars.SITE_URL'), 'uptime check remains gated on configured site URL');
assert.ok(manifest.icons[0].src.endsWith('icon.svg'), 'local app icon is declared');
assert.ok(html.includes('rel="manifest" href="./manifest.webmanifest"'), 'manifest linked from app shell');
assert.ok(html.includes("serviceWorker.register('./sw.js')"), 'service worker registration is relative');
assert.ok(worker.includes('self.registration.scope'), 'worker caches within its deployed subpath');
assert.ok(worker.includes("request.mode === 'navigate'"), 'worker has offline navigation fallback');
assert.ok(worker.includes('caches.match'), 'worker reads cached shell when offline');
assert.match(icon, /<svg/, 'local SVG icon exists');
for (const file of ['manifest.webmanifest', 'sw.js', 'icon.svg', 'progress-store.js']) {
  assert.ok(deploy.includes('cp ' + file + ' _site/' + file), 'Pages deploy includes ' + file);
}
console.log('PASS: PWA manifest, subpath-safe offline shell, local icon, and Pages deployment assets');

const fresh = progressStore.normalize(null, lessonIds);
assert.deepEqual(fresh, { version: 3, step: 0, questionId: null, score: 0, answered: false, selected: null, mistakes: [], completed: false, updatedAt: null });
const answeredState = { version: 3, step: 2, questionId: lessonIds[2], score: 1, answered: true, selected: 0, mistakes: [{ questionId: lessonIds[1], selected: 2 }], completed: false, updatedAt: '2026-10-29T00:00:00.000Z' };
assert.deepEqual(progressStore.normalize(progressStore.serialize(answeredState), lessonIds), answeredState, 'stable current question and mistakes survive reload');
const legacyV2 = progressStore.normalize(JSON.stringify({ version: 2, step: 5, score: 2, answered: true, selected: 1, mistakes: [{ questionIndex: 5, selected: 0 }], completed: false, updatedAt: '2026-10-28T00:00:00.000Z' }), lessonIds);
assert.equal(legacyV2.version, 3, 'version 2 progress migrates to version 3');
assert.equal(legacyV2.questionId, lessonIds[5], 'legacy current question is mapped to its stable ID');
assert.deepEqual(legacyV2.mistakes, [{ questionId: lessonIds[5], selected: 0 }], 'legacy mistake indexes migrate to stable IDs');
const reorderedIds = lessonIds.slice();
[reorderedIds[2], reorderedIds[5]] = [reorderedIds[5], reorderedIds[2]];
const reorderedState = { version: 3, step: 5, questionId: lessonIds[5], score: 2, answered: true, selected: 1, mistakes: [{ questionId: lessonIds[5], selected: 0 }], completed: false, updatedAt: '2026-10-29T00:00:00.000Z' };
const reordered = progressStore.normalize(JSON.stringify(reorderedState), reorderedIds);
assert.equal(reordered.step, 2, 'current question follows its ID after lesson reordering');
assert.equal(reordered.questionId, lessonIds[5], 'current question identity survives lesson reordering');
assert.deepEqual(reordered.mistakes, [{ questionId: lessonIds[5], selected: 0 }], 'mistake remains attached to the same lesson after reordering');
const removedLessonMistake = progressStore.normalize(JSON.stringify({ ...answeredState, mistakes: [{ questionId: 'removed-lesson-id', selected: 1 }] }), lessonIds);
assert.deepEqual(removedLessonMistake.mistakes, [], 'removed lesson mistakes are dropped without losing current progress');
const legacy = progressStore.normalize(JSON.stringify({ step: 3, score: 2, completed: false, updatedAt: '2026-10-28T00:00:00.000Z' }), lessonIds);
assert.equal(legacy.step, 3, 'unversioned legacy step is retained');
assert.equal(legacy.questionId, lessonIds[3], 'unversioned progress maps to the current lesson ID');
assert.equal(legacy.score, 2, 'legacy score is retained');
assert.equal(legacy.answered, false, 'legacy state migrates without inventing an answer');
assert.deepEqual(legacy.mistakes, [], 'legacy progress migrates with an empty mistake list');
const duplicateMistakes = progressStore.normalize(JSON.stringify({ ...answeredState, mistakes: [{ questionId: lessonIds[1], selected: 2 }, { questionId: lessonIds[1], selected: 0 }] }), lessonIds);
assert.deepEqual(duplicateMistakes, fresh, 'duplicate stable-ID mistake entries are rejected safely');
const invalidQuestionId = progressStore.normalize(JSON.stringify({ ...answeredState, questionId: 'unknown-current-question' }), lessonIds);
assert.deepEqual(invalidQuestionId, fresh, 'unknown current question IDs are rejected safely');
assert.deepEqual(progressStore.normalize('{bad json', lessonIds), fresh, 'corrupt saved data falls back safely');
assert.deepEqual(progressStore.normalize(JSON.stringify({ version: 3, step: 99, questionId: null, score: 0, answered: false, selected: null }), lessonIds), fresh, 'out-of-range state is rejected');
assert.ok(worker.includes("new URL('progress-store.js', APP_ROOT).href"), 'progress module is precached for offline use');
assert.ok(deploy.includes('cp progress-store.js _site/progress-store.js'), 'Pages artifact includes progress module');
console.log('PASS: progress restoration, legacy migration, corrupt/out-of-range data handling');
console.log('PASS: Arabic RTL, local persistence, 8 A1 steps, accessible feedback, responsive layout, standalone source');
